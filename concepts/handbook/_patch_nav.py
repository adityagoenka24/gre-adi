#!/usr/bin/env python3
"""Add a 'Handbook' link to the site nav, right after 'Concept Notes'.

Only touches top-level, hand-maintained pages. The /learn/ pages are
generated by build_learn.py and get the link from there instead, so they are
deliberately left alone here.

Idempotent: a page that already links to the handbook is skipped.
"""
import os
import re

ROOT = os.path.expanduser('~/mnt/gre-adi')
PAGES = ['index.html', 'pricing.html', 'diagnostic.html', 'thank-you.html',
         'sectional.html', 'previous.html', 'dashboard.html']

# the nav uses a relative href, the mobile menu the same — match both spellings
PATTERNS = [
    (r'(<a href="learn/">Concept Notes</a>)', r'\1\n      <a href="handbook/">Handbook</a>'),
    (r'(<a href="/learn/">Concept Notes</a>)', r'\1\n      <a href="/handbook/">Handbook</a>'),
]

for name in PAGES:
    path = os.path.join(ROOT, name)
    if not os.path.isfile(path):
        print(f'{name}: not found, skipped')
        continue
    html = open(path, encoding='utf-8').read()
    if 'handbook/' in html:
        print(f'{name}: already links to the handbook, skipped')
        continue
    out, hits = html, 0
    for pat, rep in PATTERNS:
        out, n = re.subn(pat, rep, out)
        hits += n
    if hits:
        open(path, 'w', encoding='utf-8').write(out)
        print(f'{name}: added {hits} handbook link(s)')
    else:
        print(f'{name}: no Concept Notes link found, left alone')
